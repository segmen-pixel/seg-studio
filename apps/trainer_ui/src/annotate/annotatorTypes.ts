export const CLASS_COLOR_PALETTE: [number, number, number][] = [
  [255, 0, 0],
  [0, 122, 255],
  [0, 200, 120],
  [255, 165, 0],
  [213, 94, 0],
  [0, 206, 209],
  [255, 20, 147],
  [128, 128, 0],
  [0, 128, 128],
  [220, 20, 60],
];

/** @deprecated Use CLASS_COLOR_PALETTE + nextPaletteColor() instead */
export const DEFAULT_CLASS_COLORS: Record<number, [number, number, number]> = {
  1: [255, 0, 0],
  2: [0, 122, 255],
  3: [0, 200, 120],
};

/** Pick the next unused color from the palette (FIFO order). */
export function nextPaletteColor(usedColors: [number, number, number][]): [number, number, number] {
  const usedSet = new Set(usedColors.map(c => `${c[0]},${c[1]},${c[2]}`));
  for (const c of CLASS_COLOR_PALETTE) {
    if (!usedSet.has(`${c[0]},${c[1]},${c[2]}`)) return c;
  }
  // All palette colors used — generate a deterministic color based on count
  const idx = usedColors.length % CLASS_COLOR_PALETTE.length;
  const base = CLASS_COLOR_PALETTE[idx]!;
  return [
    Math.min(255, base[0] + 40),
    Math.min(255, base[1] + 40),
    Math.min(255, base[2] + 40),
  ];
}
