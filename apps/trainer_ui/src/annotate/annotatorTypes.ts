export type ImageItem = {
  id: string;
  name: string;
  filename: string;
  set: "none" | "train" | "val" | "test";
  width: number;
  height: number;
  annotation?: {
    hasMask: boolean;
    /** True if mask contains non-zero (foreground) pixels.
     *  hasMask=true + hasForeground=false means "annotated as all-background". */
    hasForeground?: boolean;
    /** True only when explicitly marked clean via Mark Clean button. */
    markedClean?: boolean;
    classIds?: number[];
    revision: number;
    lastSavedAt?: string | null;
    /** True when this item was generated by the Perlin CutPaste synthesis
     *  endpoint. Synthesized items participate in training like normal
     *  labeled items but the UI adds a 🧪 badge so the user can review
     *  and delete unnatural ones. */
    synthetic?: boolean;
    /** Host image stem used as the background for this synthesized sample. */
    synthSource?: string;
    /** Stems of the labeled images whose defect crops were pasted in. */
    synthDefectSources?: string[];
  };
};

export type CacheEntry = {
  width: number;
  height: number;
  maskIndex: Uint8Array;
  touched: Uint8Array; // 1 = pixel was edited, 0 = untouched (ignore on save)
  dirty: boolean;
  revision: number;
  undoStack: { indices: Uint32Array; prevValues: Uint8Array }[];
  redoStack: { indices: Uint32Array; prevValues: Uint8Array }[];
  lastSavedAt?: string | null;
};

